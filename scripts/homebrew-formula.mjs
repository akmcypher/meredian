// Renders the Homebrew formula for a release from its macOS and Linux tarballs (built by
// scripts/package-posix.mjs). The formula installs the tarball read-only under libexec and a
// `meridian` wrapper that sets MERIDIAN_HOME, so the launcher keeps state, dependencies and the
// build in the user's own directory (see installer/posix/meridian).
// Usage: node scripts/homebrew-formula.mjs <tag> <dir-with-tarballs> <owner/repo>
//          [download-base-url]   (the base defaults to that repository's release download URL)
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const [tag, dir, repo, base] = process.argv.slice(2);
if (!tag || !dir || !repo || !/^v?[\w.-]+$/.test(tag) || !/^[\w.-]+\/[\w.-]+$/.test(repo)) {
  console.error(
    "usage: node scripts/homebrew-formula.mjs <tag> <dir> <owner/repo> [download-base-url]",
  );
  process.exit(2);
}
const downloads = base ?? `https://github.com/${repo}/releases/download/${tag}`;
const asset = (os) => {
  const name = `meridian-${tag}-${os}.tar.gz`;
  return {
    url: `${downloads}/${name}`,
    sha256: createHash("sha256")
      .update(readFileSync(join(dir, name)))
      .digest("hex"),
  };
};
const macos = asset("macos");
const linux = asset("linux");
const version = tag.replace(/^v/, "");

process.stdout.write(`# Generated by scripts/homebrew-formula.mjs for ${tag}; do not edit by hand.
class Meridian < Formula
  desc "Local preview of the Meridian Community data platform (runs in Docker)"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    url "${macos.url}"
    sha256 "${macos.sha256}"
  end

  on_linux do
    url "${linux.url}"
    sha256 "${linux.sha256}"
  end

  def install
    # .brew_home is the HOME Homebrew sets for the build, not part of the package.
    libexec.install Dir.glob("*", File::FNM_DOTMATCH) - %w[. .. .brew_home]
    (libexec/".meridian-version").write "#{version}\\n"
    (bin/"meridian").write <<~SH
      #!/bin/sh
      # State, dependencies and the build live in MERIDIAN_HOME/app, outside the Cellar.
      if [ -z "\${MERIDIAN_HOME:-}" ]; then
        case "$(uname -s)" in
          Darwin) MERIDIAN_HOME="$HOME/Library/Application Support/Meridian" ;;
          *) MERIDIAN_HOME="\${XDG_DATA_HOME:-$HOME/.local/share}/meridian" ;;
        esac
      fi
      export MERIDIAN_HOME
      exec sh "#{libexec}/meridian" "$@"
    SH
  end

  def caveats
    <<~EOS
      Meridian runs a local backend in Docker: install and start Docker Desktop (macOS) or
      Docker Engine (Linux) first. Then:
        meridian install
        meridian start
      Its data and build live in ~/Library/Application Support/Meridian/app (macOS) or
      ~/.local/share/meridian/app (Linux), not in Homebrew's prefix.
      After brew upgrade meridian, run: meridian stop && meridian upgrade
      Before brew uninstall meridian, run meridian uninstall to delete the backend and its data.
      This is a local preview, not a hosted or certified deployment.
    EOS
  end

  test do
    ENV["MERIDIAN_HOME"] = testpath/"meridian-home"
    assert_match "Meridian Community launcher", shell_output("#{bin}/meridian help")
    assert_path_exists testpath/"meridian-home/app/scripts/self-host.mjs"
  end
end
`);
